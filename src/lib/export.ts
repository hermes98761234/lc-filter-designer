/** Component-list CSV and SPICE netlist export. */
import { nearest } from './eseries'
import { formatSI, spiceNum } from './format'
import { esr, isLeaf, listParts, type Ladder, type Loss, type Node } from './ladder'

export interface PartRow {
  ref: string
  type: 'L' | 'C'
  pos: 'series' | 'shunt'
  branch: number
  exact: number
  e12: number
  e24: number
  errE12: number
  errE24: number
}

export function partRows(l: Ladder): PartRow[] {
  return listParts(l).map((p) => {
    const e12 = nearest(p.value, 'E12')
    const e24 = nearest(p.value, 'E24')
    return {
      ref: p.ref,
      type: p.type,
      pos: p.pos,
      branch: p.branch,
      exact: p.value,
      e12,
      e24,
      errE12: (e12 / p.value - 1) * 100,
      errE24: (e24 / p.value - 1) * 100,
    }
  })
}

const unit = (t: 'L' | 'C') => (t === 'L' ? 'H' : 'F')
const csvCell = (s: string | number) => (/[",\n]/.test(String(s)) ? `"${String(s).replace(/"/g, '""')}"` : String(s))

export function toCsv(l: Ladder): string {
  const rows = partRows(l)
  const head = ['Ref', 'Type', 'Placement', 'Branch', 'Exact (SI)', 'Exact', 'E12 (SI)', 'E12', 'E12 error %', 'E24 (SI)', 'E24', 'E24 error %']
  const lines = [head.join(',')]
  for (const r of rows) {
    lines.push(
      [
        r.ref,
        r.type === 'L' ? 'Inductor' : 'Capacitor',
        r.pos,
        r.branch,
        r.exact.toPrecision(6),
        formatSI(r.exact, unit(r.type)),
        r.e12.toPrecision(3),
        formatSI(r.e12, unit(r.type)),
        r.errE12.toFixed(2),
        r.e24.toPrecision(3),
        formatSI(r.e24, unit(r.type)),
        r.errE24.toFixed(2),
      ]
        .map(csvCell)
        .join(','),
    )
  }
  lines.push(['Rs', 'Resistor', 'source', '', l.rs.toPrecision(6), formatSI(l.rs, 'Ω'), '', '', '', '', '', ''].map(csvCell).join(','))
  lines.push(['RL', 'Resistor', 'load', '', l.rl.toPrecision(6), formatSI(l.rl, 'Ω'), '', '', '', '', '', ''].map(csvCell).join(','))
  return lines.join('\n') + '\n'
}

export interface SpiceOptions {
  title: string
  fmin: number
  fmax: number
  loss?: Loss
  /** Points per decade. */
  ppd?: number
}

/** SPICE netlist (ngspice / LTspice compatible) for the ladder. */
export function toSpice(l: Ladder, o: SpiceOptions): string {
  const out: string[] = []
  let nn = 0
  let nr = 0
  const newNode = () => `n${++nn}`
  const comp = (n: Node, a: string, b: string) => {
    if (isLeaf(n)) {
      const r = o.loss ? esr(n.t, n.v, o.loss) : 0
      const name = n.t === 'L' ? `L${n.ref.slice(1)}` : `C${n.ref.slice(1)}`
      if (r > 0) {
        const m = newNode()
        out.push(`${name} ${a} ${m} ${spiceNum(n.v)}`)
        out.push(`R${n.t === 'L' ? 'esrL' : 'esrC'}${n.ref.slice(1)} ${m} ${b} ${spiceNum(r)}`)
      } else out.push(`${name} ${a} ${b} ${spiceNum(n.v)}`)
    } else if (n.t === 'P') n.k.forEach((c) => comp(c, a, b))
    else {
      let cur = a
      n.k.forEach((c, i) => {
        const nxt = i === n.k.length - 1 ? b : newNode()
        comp(c, cur, nxt)
        cur = nxt
      })
    }
  }
  out.push(`* ${o.title}`)
  out.push('* Generated by LC Filter Designer (https://hermes98761234.github.io/lc-filter-designer/)')
  out.push(`* S21 [dB] = 20*log10(2*|V(out)|*sqrt(${spiceNum(l.rs)}/${spiceNum(l.rl)}))  (Vs = 1 V AC)`)
  out.push('Vs vs 0 AC 1')
  out.push(`Rs vs in ${spiceNum(l.rs)}`)
  let cur = 'in'
  l.branches.forEach((b, i) => {
    if (b.pos === 'series') {
      const nxt = i === l.branches.length - 1 ? 'out' : newNode()
      comp(b.node, cur, nxt)
      cur = nxt
    } else {
      comp(b.node, cur, '0')
      if (i === l.branches.length - 1) {
        // Output node is the last shunt node; tie it to the named output node.
        out.push(`Rtie${++nr} ${cur} out 1u`)
      }
    }
  })
  out.push(`Rload out 0 ${spiceNum(l.rl)}`)
  out.push(`.ac dec ${o.ppd ?? 100} ${spiceNum(o.fmin)} ${spiceNum(o.fmax)}`)
  out.push('.end')
  return out.join('\n') + '\n'
}
